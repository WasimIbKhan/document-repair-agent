import argparse
import sys
from datetime import date
from pathlib import Path

from .ground_truth import is_template, parse_ground_truth_text
from .schema import LayoutDoc
from .scoring import parser_toc, score
from .splits import EVALS_DIR, SPLITS, load_splits

PREDICTORS = {"parser": parser_toc}
PREDICTOR_NOTES = {
    "parser": "headings in the content list Enlighten stores today (parser output after the app's current repair step)",
}


def load_case(case_dir: Path) -> tuple[LayoutDoc, list[dict]] | None:
    gt_path, layout_path = case_dir / "ground_truth_toc.txt", case_dir / "layout.json"
    if not gt_path.exists() or not layout_path.exists():
        return None
    text = gt_path.read_text(encoding="utf-8")
    if is_template(text):
        return None
    layout = LayoutDoc.model_validate_json(layout_path.read_text(encoding="utf-8"))
    return layout, parse_ground_truth_text(text)


def run(predictors: list[str], splits: list[str], cases_dir: Path = EVALS_DIR / "cases") -> list[dict]:
    rows = []
    assignment = load_splits()
    for split in splits:
        for doc_id in assignment[split]:
            loaded = load_case(cases_dir / doc_id)
            if loaded is None:
                rows.append({"split": split, "case": doc_id, "predictor": "-", "skipped": "no answer key yet"})
                continue
            layout, truth = loaded
            for name in predictors:
                rows.append({"split": split, "case": doc_id, "predictor": name,
                             **score(PREDICTORS[name](layout), truth)})
    return rows


def table(rows: list[dict]) -> str:
    out = ["| split | case | predictor | precision | recall | level acc | matched / truth | predicted | pass |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if "skipped" in r:
            out.append(f"| {r['split']} | {r['case']} | - | - | - | - | - | - | {r['skipped']} |")
            continue
        out.append(f"| {r['split']} | {r['case']} | {r['predictor']} | {r['precision']:.2f} | {r['recall']:.2f} | "
                   f"{r['level_accuracy']:.2f} | {r['n_matched']} / {r['n_truth']} | {r['n_predicted']} | "
                   f"{'yes' if r['passed'] else 'no'} |")
    return "\n".join(out)


def details(rows: list[dict], limit: int = 8) -> str:
    out = []
    for r in rows:
        if "skipped" in r:
            continue
        out.append(f"\n### {r['case']} / {r['predictor']}\n")
        for key, label in (("missed", "missed"), ("wrong_page", "wrong page"),
                           ("wrong_level", "wrong level"), ("extra", "extra")):
            items = r[key]
            if not items:
                continue
            shown = "; ".join(repr(i["title"][:50]) for i in items[:limit])
            more = f" (+{len(items) - limit} more)" if len(items) > limit else ""
            out.append(f"- {label} ({len(items)}): {shown}{more}")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Score predicted TOCs against the answer keys")
    ap.add_argument("--predictor", action="append", choices=sorted(PREDICTORS))
    ap.add_argument("--split", action="append", choices=SPLITS)
    ap.add_argument("--no-write", action="store_true", help="print only, do not rewrite evals/results.md")
    args = ap.parse_args(argv)
    rows = run(args.predictor or ["parser"], args.split or list(SPLITS))
    body = table(rows)
    print(body)
    if not args.no_write:
        notes = "\n".join(f"- `{k}`: {v}" for k, v in PREDICTOR_NOTES.items())
        (EVALS_DIR / "results.md").write_text(
            f"# Results\n\nGenerated by `evals/run_evals.py` on {date.today().isoformat()}.\n\n"
            f"A predicted entry matches an answer-key entry when the titles agree (fuzzy ratio >= 90 after "
            f"lowercasing and folding diacritics) and the PDF page is the same. Levels are compared by nesting "
            f"depth. Pass = precision and recall both >= 0.9.\n\n{notes}\n\n{body}\n\n## Details\n{details(rows)}\n",
            encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
